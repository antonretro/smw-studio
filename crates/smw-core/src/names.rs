//! Level names as the game shows them on the overworld, read from the ROM: the original
//! game builds each name from up to three word pieces; Lunar Magic (once names are edited)
//! keeps 19 tiles per level in a table its own routine reads.

/// Level number of overworld level ("translevel") `t`: 00-24 are levels 000-024, the rest
/// 101-13B.
pub fn level_of(t: u16) -> u16 {
    if t < 0x25 { t } else { t + 0xDC }
}

