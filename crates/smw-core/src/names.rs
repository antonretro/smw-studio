/// Name tiles of every overworld level, or None if the ROM's name code isn't one we know.
/// `read` reads a byte at a SNES address.
pub fn name_tiles(read: &dyn Fn(u32) -> Option<u8>) -> Option<Vec<[u8; 19]>> {
    let r16 = |a: u32| Some(read(a)? as u16 | (read(a + 1)? as u16) << 8);
    // The original game calls its name routine with JSR $9D07 at $048E88
    if [0x048E88, 0x048E89, 0x048E8A].map(read) == [Some(0x20), Some(0x07), Some(0x9D)] {
        // JSR $9D07: the original word-piece names
        let mut out = Vec::new();
        for t in 0..0x60u32 {
            let w = r16(0x04A0FC + t * 2)?;
            let piece = |table: u32, i: u16| -> Option<Vec<u8>> {
                let mut a = 0x049AC5 + r16(table + i as u32 * 2)? as u32;
                let mut v = Vec::new();
                while v.len() < 32 {
                    let c = read(a)?;
                    a += 1;
                    v.push(c & 0x7F);
                    if c & 0x80 != 0 {
                        break;
                    }
                }
                Some(v)
            };
            let mut tiles = Vec::new();
            let p1 = piece(0x049C91, (w >> 8) & 0x7F)?;
            if read(0x049AC5 + r16(0x049C91 + ((w >> 8) & 0x7F) as u32 * 2)? as u32)? < 0x80 {
                tiles.extend(p1);
            }
            let p2 = piece(0x049CCF, (w & 0xF0) >> 4)?;
            if read(0x049AC5 + r16(0x049CCF + ((w & 0xF0) >> 3) as u32)? as u32)? != 0x9F {
                tiles.extend(p2);
            }
            tiles.extend(piece(0x049CED, w & 0x0F)?);
            tiles.resize(19.max(tiles.len()), 0x1F);
            out.push(tiles[..19].try_into().unwrap());
        }
        return Some(out);
    }
    // Lunar Magic replaces that part with a JSL to its routine, which reads the names
    // with LDA long,X
    if let Some(at) = (0x048E70..0x048E8B).find(|&a| read(a) == Some(0x22)) {
        let target = read(at + 1)? as u32 | (read(at + 2)? as u32) << 8 | (read(at + 3)? as u32) << 16;
        let table = (target..target + 0x60).find(|&a| read(a) == Some(0xBF))?;
        let table = read(table + 1)? as u32 | (read(table + 2)? as u32) << 8 | (read(table + 3)? as u32) << 16;
        return (0..0x60u32).map(|t| (0..19u32).map(|i| read(table + t * 19 + i)).collect::<Option<Vec<u8>>>().map(|v| v.try_into().unwrap())).collect();
    }
    None
}

/// Tiles as text: the overworld font has A-Z, digits and a few signs; anything else (icons,
/// coloured letters) is left out, except the original "YELLOW" picture.
pub fn text(tiles: &[u8]) -> String {
    let mut s = String::new();
    let mut i = 0;
    while i < tiles.len() {
        let c = tiles[i];
        if tiles[i..].starts_with(&[0x38, 0x39, 0x3A, 0x3B, 0x3C]) {
            s += "YELLOW";
            i += 5;
            continue;
        }
        match c {
            0x00..=0x19 => s.push((b'A' + c) as char),
            0x1C => s.push('-'),
            0x1F => s.push(' '),
            0x5A => s.push('#'),
            0x5D => s.push('\''),
            0x63..=0x6C => s.push((b'0' + c - 0x63) as char),
            _ => {}
        }
        i += 1;
    }
    // "DONUT PLAINS 1" -> "Donut Plains 1"
    let mut out = String::new();
    let mut start = true;
    for ch in s.trim().chars() {
        out.push(if start { ch } else { ch.to_ascii_lowercase() });
        start = !ch.is_ascii_alphanumeric() && ch != '\'';
    }
    out.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Names that differ from the original game's (so a hack's own names, not leftovers), by
/// level number.
pub fn custom_names(read: &dyn Fn(u32) -> Option<u8>) -> Vec<(u16, String)> {
    let Some(tiles) = name_tiles(read) else { return vec![] };
    tiles
        .iter()
        .enumerate()
        .filter(|(t, n)| text(&n[..]) != text(&VANILLA[*t]))
        .map(|(t, n)| (level_of(t as u16), text(&n[..])))
        .filter(|(_, s)| !s.is_empty())
        .collect()
}
